/**
 * Devuelve un User-Agent aleatorio de entre una lista de cadenas reales
 * recogidas de navegadores de escritorio ampliamente utilizados.
 *
 * Útil para enmascarar peticiones HTTP salientes y evitar bloqueos por
 * parte de servidores que filtran agentes no reconocidos.
 *
 * @returns Cadena `User-Agent` seleccionada al azar.
 */
export function randomUA(): string {
    return UA[Math.floor(Math.random() * UA.length)];
}

